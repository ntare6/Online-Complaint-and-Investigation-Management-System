function setLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('civicLang', lang);
    const s = translations[lang];

    // Translate all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!s[key]) return;
        const tag = el.tagName;
        if ((tag === 'INPUT' || tag === 'TEXTAREA') && el.hasAttribute('placeholder')) {
            el.setAttribute('placeholder', s[key]);
        } else if (tag !== 'SELECT') {
            el.innerText = s[key];
        }
    });

    // Translate select first-option placeholders via data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (s[key] && el.options && el.options[0]) {
            el.options[0].text = s[key];
        }
    });

    // Sync all language selectors on the page
    document.querySelectorAll('.lang-select').forEach(sel => { sel.value = lang; });
}

document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('civicLang') || 'en';
    setLanguage(saved);
});
